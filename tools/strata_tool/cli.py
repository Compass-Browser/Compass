"""The `strata` command line."""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

from . import checkout, overrides, patches
from .layout import CONFIGS, Layout, detect
from .process import CommandError, depot_tool, run

DEFAULT_TARGET = 'chrome'
TEST_TARGET = 'strata_unittests'


def wrapper_python(layout: Layout) -> str:
  """The Python used for cc_wrapper: depot_tools' own if available."""
  reldir = layout.depot_tools / 'python3_bin_reldir.txt'
  if reldir.is_file():
    exe = 'python3.exe' if sys.platform == 'win32' else 'python3'
    candidate = layout.depot_tools / reldir.read_text().strip() / exe
    if candidate.is_file():
      return candidate.as_posix()
  return Path(sys.executable).as_posix()


def args_gn(layout: Layout, config: str, cpu: str | None) -> str:
  lines = [
      '# Generated by `strata gen %s`. Shared settings live in' % config,
      '# //strata/config/args/; add local tweaks at the end of this file.',
      'import("//strata/config/args/common.gn")',
      'import("//strata/config/args/%s.gn")' % config,
      'cc_wrapper = "%s ../../strata/build/redirect_cc.py"' %
      wrapper_python(layout),
  ]
  if cpu:
    lines.append('target_cpu = "%s"' % cpu)
  return '\n'.join(lines) + '\n'


def product_name(layout: Layout) -> str:
  branding = layout.src / 'chrome/app/theme/chromium/BRANDING'
  for line in branding.read_text().splitlines():
    if line.startswith('PRODUCT_FULLNAME='):
      return line.split('=', 1)[1]
  return 'Chromium'


def browser_binary(layout: Layout, out_dir: Path) -> Path:
  if sys.platform == 'darwin':
    name = product_name(layout)
    return out_dir / (name + '.app') / 'Contents' / 'MacOS' / name
  if sys.platform == 'win32':
    return out_dir / 'chrome.exe'
  return out_dir / 'chrome'


def require_lowercase_name(layout: Layout) -> None:
  # Includes are spelled "strata/...". Clang resolves the src/strata link and
  # rejects a differently cased directory (-Wnonportable-include-path).
  if layout.root.name != 'strata':
    raise CommandError('the repository directory must be named "strata" '
                       '(it is "%s"); rename it and re-run' % layout.root.name)


def require_checkout(layout: Layout) -> None:
  if not (layout.src / '.gn').is_file():
    raise CommandError('no Chromium checkout at %s; run `strata init` first' %
                       layout.src)


def cmd_info(layout: Layout, _args) -> None:
  print('repository:       %s' % layout.root)
  print('chromium dir:     %s' % layout.chromium_dir)
  print('layout:           %s' % ('in-tree' if layout.in_tree else 'linked'))
  print('chromium version: %s' % layout.chromium_version())
  print('checkout present: %s' % (layout.src / '.gn').is_file())


def cmd_init(layout: Layout, args) -> None:
  require_lowercase_name(layout)
  checkout.init(layout, args.target_os or [checkout.host_os()])
  print('\nDone. Next: strata gen debug && strata build')


def cmd_sync(layout: Layout, _args) -> None:
  require_checkout(layout)
  failures = checkout.update(layout, layout.chromium_version())
  if failures:
    raise CommandError('%d patch(es) failed to apply' % len(failures))


def cmd_update_chromium(layout: Layout, args) -> None:
  require_checkout(layout)
  failures = checkout.update(layout, args.version)
  if failures:
    print('\n%d patch(es) need manual fixes. Resolve the conflicts in src/, '
          'then run `strata patches export`.' % len(failures))
    sys.exit(1)
  orphaned = overrides.orphans(layout.overrides_dir, layout.src)
  if orphaned:
    print('\nOverrides whose upstream file no longer exists:\n  ' +
          '\n  '.join(orphaned))
  print('\nNow on %s. Build, test, then commit patches/ and '
        'config/chromium_version.' % args.version)


def cmd_patches(layout: Layout, args) -> None:
  require_checkout(layout)
  if args.action == 'apply':
    failures = patches.apply(layout.patches_dir, layout.src, args.three_way)
    if failures:
      raise CommandError('%d patch(es) failed to apply' % len(failures))
  elif args.action == 'revert':
    if patches.revert(layout.patches_dir, layout.src):
      raise CommandError('some patches could not be reverted')
  elif args.action == 'export':
    patches.export(layout.patches_dir, layout.src, args.repo or [])
  else:
    for patch, state in patches.status(layout.patches_dir,
                                       layout.src).items():
      print('%-12s %s' % (state,
                          patch.relative_to(layout.patches_dir).as_posix()))


def cmd_gen(layout: Layout, args) -> None:
  require_lowercase_name(layout)
  require_checkout(layout)
  out_dir = layout.out_dir(args.config)
  args_file = out_dir / 'args.gn'
  if args.force or not args_file.exists():
    out_dir.mkdir(parents=True, exist_ok=True)
    args_file.write_text(args_gn(layout, args.config, args.cpu))
  run([depot_tool('gn'), 'gen', out_dir.relative_to(layout.src).as_posix()],
      layout.src, env=layout.env())


def build(layout: Layout, config: str, targets, jobs: int | None = None) -> Path:
  require_checkout(layout)
  out_dir = layout.out_dir(config)
  if not (out_dir / 'args.gn').exists():
    raise CommandError('%s is not set up; run `strata gen %s`' %
                       (out_dir, config))
  for path in overrides.orphans(layout.overrides_dir, layout.src):
    print('warning: override has no upstream file: chromium_src/' + path)
  for path in overrides.sync(layout.overrides_dir, layout.src, out_dir):
    print('override changed, rebuilding: ' + path)
  jobs_args = ['-j', str(jobs)] if jobs else []
  run([depot_tool('autoninja'), '-C', out_dir] + jobs_args + list(targets),
      layout.src, env=layout.env())
  return out_dir


def cmd_build(layout: Layout, args) -> None:
  build(layout, args.config, args.targets or [DEFAULT_TARGET], args.jobs)


def cmd_run(layout: Layout, args) -> None:
  out_dir = layout.out_dir(args.config)
  binary = browser_binary(layout, out_dir)
  if not binary.exists():
    raise CommandError('%s not found; run `strata build`' % binary)
  profile = out_dir / 'strata-dev-profile'
  if args.fresh and profile.exists():
    shutil.rmtree(profile)
  run([binary, '--user-data-dir=%s' % profile] + args.browser_args,
      layout.src, check=False)


def cmd_test(layout: Layout, args) -> None:
  out_dir = build(layout, args.config, [TEST_TARGET], args.jobs)
  exe = TEST_TARGET + ('.exe' if sys.platform == 'win32' else '')
  result = run([out_dir / exe] + args.test_args, layout.src, check=False)
  sys.exit(result.returncode)


def add_jobs_argument(p: argparse.ArgumentParser) -> None:
  default = os.environ.get('STRATA_JOBS')
  p.add_argument('-j', '--jobs', type=int,
                 default=int(default) if default else None,
                 help='parallel build jobs (default: $STRATA_JOBS, else '
                 'autoninja picks one per core). Lower it if the machine '
                 'runs out of memory.')


def parser() -> argparse.ArgumentParser:
  p = argparse.ArgumentParser(prog='strata',
                              description='Build and maintain Strata.')
  sub = p.add_subparsers(dest='command', required=True)

  sub.add_parser('info', help='show checkout paths and version').set_defaults(
      func=cmd_info)

  s = sub.add_parser('init', help='fetch depot_tools and Chromium, apply '
                     'patches')
  s.add_argument('--target-os', action='append',
                 help='extra target OS for gclient (mac, win, linux, …)')
  s.set_defaults(func=cmd_init)

  sub.add_parser('sync', help='re-sync the checkout to the pinned version '
                 'and re-apply patches').set_defaults(func=cmd_sync)

  s = sub.add_parser('update-chromium', help='move to a new Chromium tag')
  s.add_argument('version', help='e.g. 156.0.8078.48')
  s.set_defaults(func=cmd_update_chromium)

  s = sub.add_parser('patches', help='manage patches/')
  s.add_argument('action', choices=['apply', 'revert', 'export', 'status'])
  s.add_argument('--three-way', action='store_true',
                 help='apply: fall back to a 3-way merge')
  s.add_argument('--repo', action='append',
                 help='export: also export this nested repo (e.g. v8)')
  s.set_defaults(func=cmd_patches)

  s = sub.add_parser('gen', help='write args.gn and run gn gen')
  s.add_argument('config', choices=sorted(CONFIGS), nargs='?', default='debug')
  s.add_argument('--cpu', help='target_cpu, e.g. arm64 or x64')
  s.add_argument('--force', action='store_true',
                 help='overwrite an existing args.gn')
  s.set_defaults(func=cmd_gen)

  s = sub.add_parser('build', help='build with autoninja')
  s.add_argument('targets', nargs='*', help='default: ' + DEFAULT_TARGET)
  s.add_argument('-c', '--config', choices=sorted(CONFIGS), default='debug')
  add_jobs_argument(s)
  s.set_defaults(func=cmd_build)

  s = sub.add_parser('run', help='launch the built browser')
  s.add_argument('-c', '--config', choices=sorted(CONFIGS), default='debug')
  s.add_argument('--fresh', action='store_true',
                 help='start from an empty dev profile')
  s.add_argument('browser_args', nargs=argparse.REMAINDER)
  s.set_defaults(func=cmd_run)

  s = sub.add_parser('test', help='build and run strata_unittests')
  s.add_argument('-c', '--config', choices=sorted(CONFIGS), default='debug')
  add_jobs_argument(s)
  s.add_argument('test_args', nargs=argparse.REMAINDER)
  s.set_defaults(func=cmd_test)
  return p


def main(argv=None) -> int:
  args = parser().parse_args(argv)
  try:
    args.func(detect(), args)
  except CommandError as e:
    print('error: %s' % e, file=sys.stderr)
    return 1
  return 0
