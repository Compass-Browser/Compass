"""Writes the Compass glyph as a Chromium vector icon (.icon).

  tools/branding/make_icon.py > out.icon

The two ribbons of assets/compass_glyph.svg, in one color, scaled so the
glyph spans 20 of the canvas's 24 units, as upstream's product icon does.
svg() gives the same glyph as a one-color SVG.

Each ribbon is a path of its own: the two wind opposite ways, so as one
path their overlap would cancel out and show what's behind the icon.
"""

import math

# The ribbons' outlines, from assets/compass_glyph.svg: a start point, then
# circular arcs (radius, large arc, sweep, end x, end y).
RIBBONS = [
    [(271.58, 417.94), (275, 0, 0, 734.36, 696.01), (70, 0, 0, 630.32, 602.33),
     (135, 0, 1, 403.14, 465.83), (70, 0, 0, 271.58, 417.94)],
    [(734.36, 327.99), (275, 0, 0, 280.77, 628.22), (70, 0, 0, 407.65, 569.05),
     (135, 0, 1, 630.32, 421.67), (70, 0, 0, 734.36, 327.99)],
]
CANVAS = 24
SPAN = 20


def arc_points(start, arc, steps=200):
  """Points along an SVG circular arc (endpoint parameterization)."""
  (x1, y1), (r, large, sweep, x2, y2) = start, arc
  hx, hy = (x1 - x2) / 2, (y1 - y2) / 2
  factor = math.sqrt(max(r * r / (hx * hx + hy * hy) - 1, 0))
  if large == sweep:
    factor = -factor
  cx = factor * hy + (x1 + x2) / 2
  cy = -factor * hx + (y1 + y2) / 2
  a1 = math.atan2(y1 - cy, x1 - cx)
  delta = math.atan2(y2 - cy, x2 - cx) - a1
  if sweep and delta < 0:
    delta += 2 * math.pi
  if not sweep and delta > 0:
    delta -= 2 * math.pi
  return [(cx + r * math.cos(a1 + delta * i / steps),
           cy + r * math.sin(a1 + delta * i / steps))
          for i in range(steps + 1)]


def bounds():
  points = []
  for ribbon in RIBBONS:
    start = ribbon[0]
    for arc in ribbon[1:]:
      points += arc_points(start, arc)
      start = arc[3:]
  xs = [x for x, _ in points]
  ys = [y for _, y in points]
  return min(xs), min(ys), max(xs), max(ys)


def _n(value):
  return ('%.2f' % value).rstrip('0').rstrip('.')


def _transform(canvas, span):
  """The scale and offsets that fit the glyph's |span| in a |canvas| square."""
  left, top, right, bottom = bounds()
  scale = span / max(right - left, bottom - top)
  dx = canvas / 2 - (left + right) / 2 * scale
  dy = canvas / 2 - (top + bottom) / 2 * scale
  return scale, dx, dy


def icon():
  """The glyph as a vector icon, on a 24-unit canvas."""
  scale, dx, dy = _transform(CANVAS, SPAN)
  lines = [
      '// Copyright 2026 The Compass Authors',
      '// Use of this source code is governed by a BSD-style license that can be',
      '// found in the LICENSE file.',
      '// Generated by compass/tools/branding/make_icon.py.',
      '',
      'CANVAS_DIMENSIONS, %d,' % CANVAS,
  ]
  for i, ribbon in enumerate(RIBBONS):
    if i:
      lines.append('NEW_PATH,')
    x, y = ribbon[0]
    lines.append('MOVE_TO, %s, %s,' % (_n(x * scale + dx), _n(y * scale + dy)))
    for r, large, sweep, x, y in ribbon[1:]:
      lines.append('ARC_TO, %s, %s, 0, %d, %d, %s, %s,' %
                   (_n(r * scale), _n(r * scale), large, sweep,
                    _n(x * scale + dx), _n(y * scale + dy)))
    lines.append('CLOSE,')
  return '\n'.join(lines) + '\n'


def svg(size=16):
  """The glyph in black on a |size| px square, with the same margin as the
  vector icon: for WebUI, which draws such icons as masks or plain images."""
  scale, dx, dy = _transform(size, SPAN * size / CANVAS)
  paths = []
  for ribbon in RIBBONS:
    d = []
    x, y = ribbon[0]
    d.append('M%s %s' % (_n(x * scale + dx), _n(y * scale + dy)))
    for r, large, sweep, x, y in ribbon[1:]:
      d.append('A%s %s 0 %d %d %s %s' %
               (_n(r * scale), _n(r * scale), large, sweep,
                _n(x * scale + dx), _n(y * scale + dy)))
    d.append('Z')
    paths.append('<path fill="#000" d="%s"/>' % ''.join(d))
  return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
          'viewBox="0 0 %d %d">%s</svg>\n' %
          (size, size, size, size, ''.join(paths)))


def main():
  print(icon(), end='')


if __name__ == '__main__':
  main()
