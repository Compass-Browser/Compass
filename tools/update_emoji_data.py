"""Writes resources/sidebar/emoji_data.ts, the space emoji picker's emoji.

  update_emoji_data.py [--emoji-test FILE] [--annotations FILE]
                       [--derived FILE]

Reads Unicode's emoji-test.txt (the emoji, their order and groups) and
CLDR's English annotations (names and search keywords), downloading the
latest of each unless given files. Keeps the fully-qualified emoji up to
MAX_VERSION, without skin tone variants, and prints how many it wrote.
See docs/design/spaces.md, "Space icons".
"""

import argparse
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree

EMOJI_TEST_URL = 'https://unicode.org/Public/emoji/latest/emoji-test.txt'
CLDR = 'https://raw.githubusercontent.com/unicode-org/cldr/main/common'
ANNOTATIONS_URL = CLDR + '/annotations/en.xml'
DERIVED_URL = CLDR + '/annotationsDerived/en.xml'

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'resources', 'sidebar', 'emoji_data.ts')

# The newest emoji offered. Pages draw emoji with the system's font, and
# later ones are missing from macOS 13 and Windows 11's (a box instead).
MAX_VERSION = (15, 0)
# SpaceIcon::kMaxEmojiBytes (browser/sidebar/space_model.h).
MAX_BYTES = 64
SKIN_TONES = set(range(0x1F3FB, 0x1F400))
# emoji-test.txt's groups, in its order, as the picker's tabs: the name
# shown and the emoji on the tab. "Component" (skin tones, hair) is left out.
GROUPS = {
    'Smileys & Emotion': ('smileys', 'Smileys & emotion', '😀'),
    'People & Body': ('people', 'People & body', '👋'),
    'Animals & Nature': ('nature', 'Animals & nature', '🐻'),
    'Food & Drink': ('food', 'Food & drink', '🍔'),
    'Travel & Places': ('travel', 'Travel & places', '✈️'),
    'Activities': ('activities', 'Activities', '⚽'),
    'Objects': ('objects', 'Objects', '💡'),
    'Symbols': ('symbols', 'Symbols', '🔣'),
    'Flags': ('flags', 'Flags', '🏳️'),
}

LINE = re.compile(r'^([0-9A-F ]+?)\s*;\s*([a-z-]+)\s*#\s*\S+\s+E(\d+)\.(\d+)'
                  r'\s+(.+)$')


def fetch(url):
  request = urllib.request.Request(url, headers={'User-Agent': 'compass-tools'})
  with urllib.request.urlopen(request, timeout=60) as response:
    return response.read().decode('utf-8')


def parse_emoji_test(text):
  """[(group, [(emoji, name)])] for the emoji the picker offers."""
  groups = []
  current = None
  for line in text.splitlines():
    if line.startswith('# group: '):
      name = line[len('# group: '):].strip()
      current = [] if name in GROUPS else None
      if current is not None:
        groups.append((name, current))
      continue
    match = LINE.match(line)
    if not match or current is None:
      continue
    points, status, major, minor, name = match.groups()
    if status != 'fully-qualified':
      continue
    if (int(major), int(minor)) > MAX_VERSION:
      continue
    codes = [int(p, 16) for p in points.split()]
    if SKIN_TONES.intersection(codes):
      continue
    emoji = ''.join(chr(c) for c in codes)
    if len(emoji.encode('utf-8')) > MAX_BYTES:
      raise ValueError('%s is longer than %d bytes' % (name, MAX_BYTES))
    current.append((emoji, name.strip()))
  missing = set(GROUPS) - {name for name, _ in groups}
  if missing:
    raise ValueError('emoji-test.txt: no group %s' % ', '.join(sorted(missing)))
  return groups


def parse_annotations(*texts):
  """{emoji without U+FE0F: (name or None, [keywords])} from CLDR's XML."""
  result = {}
  for text in texts:
    root = ElementTree.fromstring(text.encode('utf-8'))
    for node in root.iter('annotation'):
      cp = node.get('cp')
      name, keywords = result.get(cp, (None, []))
      if node.get('type') == 'tts':
        name = (node.text or '').strip()
      else:
        keywords = [k.strip() for k in (node.text or '').split('|')]
      result[cp] = (name, keywords)
  return result


def search_words(name, keywords):
  """The keywords that add something to |name|, lower case, one string."""
  seen = set(name.lower().split())
  words = []
  for keyword in keywords:
    keyword = keyword.lower()
    if keyword and keyword not in seen:
      seen.add(keyword)
      words.append(keyword)
  return ' '.join(words)


def build(emoji_test, annotations):
  """The module's text, and how many emoji it has."""
  count = 0
  out = [
      '// Copyright 2026 The Compass Authors',
      '// Use of this source code is governed by a BSD-style license that '
      'can be',
      '// found in the LICENSE file.',
      '',
      '// Generated by tools/update_emoji_data.py: do not edit. From '
      "Unicode's",
      '// emoji-test.txt and CLDR\'s English annotations, under the Unicode '
      'License',
      '// (third_party/unicode_emoji/LICENSE).',
      '//',
      '// Each group\'s |emoji| is one line per emoji: the emoji, its name '
      'and',
      '// its search keywords, separated by tabs.',
      '',
      'export interface EmojiGroupData {',
      '  id: string;',
      '  label: string;',
      '  icon: string;',
      '  emoji: string;',
      '}',
      '',
      'export const EMOJI_GROUPS: EmojiGroupData[] = [',
  ]
  for group, entries in emoji_test:
    gid, label, icon = GROUPS[group]
    lines = []
    for emoji, fallback in entries:
      name, keywords = annotations.get(emoji.replace('️', ''),
                                       (None, []))
      name = name or fallback
      if '\t' in name or '\n' in name:
        raise ValueError('%r: tab or newline in name' % name)
      lines.append('\t'.join([emoji, name, search_words(name, keywords)]))
      count += 1
    out.append('  {')
    out.append('    id: %s,' % json.dumps(gid))
    out.append('    label: %s,' % json.dumps(label))
    out.append('    icon: %s,' % json.dumps(icon, ensure_ascii=False))
    out.append('    emoji: %s,' %
               json.dumps('\n'.join(lines), ensure_ascii=False))
    out.append('  },')
  out.append('];')
  out.append('')
  return '\n'.join(out), count


def read(path, url):
  if path:
    with open(path, encoding='utf-8') as f:
      return f.read()
  return fetch(url)


def main():
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument('--emoji-test', help='a local emoji-test.txt')
  parser.add_argument('--annotations', help="a local CLDR annotations/en.xml")
  parser.add_argument('--derived',
                      help='a local CLDR annotationsDerived/en.xml')
  args = parser.parse_args()

  emoji_test = parse_emoji_test(read(args.emoji_test, EMOJI_TEST_URL))
  annotations = parse_annotations(read(args.annotations, ANNOTATIONS_URL),
                                  read(args.derived, DERIVED_URL))
  text, count = build(emoji_test, annotations)
  with open(OUT, 'w', encoding='utf-8') as f:
    f.write(text)
  print('%d emoji' % count)
  return 0


if __name__ == '__main__':
  sys.exit(main())
