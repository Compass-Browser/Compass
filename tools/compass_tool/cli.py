def ios_external(args, build_number) -> None:
  """Sends an uploaded build (the newest when `build_number` is None) to
  external testers: What to Test, the external group, Beta App Review."""
  from . import testflight
  if not (args.api_key and args.api_key_id and args.api_issuer):
    raise CommandError('external testing needs --api-key, --api-key-id and '
                       '--api-issuer')
  what = {}
  if args.what_to_test_file:
    # WhatToTest.txt is en-US; WhatToTest.<locale>.txt beside it (it, de,
    # fr-FR...) are its translations.
    path = Path(args.what_to_test_file)
    what[testflight.LOCALE] = path.read_text().strip()
    for other in sorted(path.parent.glob('%s.*%s' % (path.stem, path.suffix))):
      locale = other.name[len(path.stem) + 1:-len(path.suffix) or None]
      if locale and '.' not in locale and other.read_text().strip():
        what[locale] = other.read_text().strip()
  else:
    what[testflight.LOCALE] = (args.what_to_test or '').strip()
  if not what[testflight.LOCALE]:
    raise CommandError('external testing needs --what-to-test or '
                       '--what-to-test-file')
  key = Path(args.api_key).resolve()
  client = testflight.Client(lambda: testflight.make_token(
      key, args.api_key_id, args.api_issuer))
  testflight.submit_external(client, IOS_BUNDLE_ID, build_number, args.group,
                             what)


def ios_archive(ios: Path, args) -> str:
  """A Release archive exported for App Store Connect (TestFlight), signed
  automatically with the team in project.yml. The build number is the time,
  so every upload is higher than the last."""
  import plistlib
  import time
  out = ios / 'build' / 'archive'
  if out.exists():
    shutil.rmtree(out)
  out.mkdir(parents=True)
  archive = out / 'Compass.xcarchive'
  auth = ios_auth_args(args)
  # Date.time, e.g. 20261101.1114: always higher than the last upload.
  build_number = time.strftime('%Y%m%d.%H%M')
  run(['xcodebuild', '-quiet', '-project', 'Compass.xcodeproj', '-scheme',
       'Compass', '-configuration', 'Release', '-destination',
       'generic/platform=iOS', '-archivePath', archive,
       '-derivedDataPath', ios / 'build' / 'DerivedData-archive',
       'CURRENT_PROJECT_VERSION=' + build_number, 'archive'] +
      ios_xcconfig_args(ios) + auth, ios)
  options = out / 'ExportOptions.plist'
  options.write_bytes(plistlib.dumps({
      'method': 'app-store-connect',
      'destination': 'upload' if args.upload else 'export',
      'teamID': IOS_TEAM,
      'signingStyle': 'automatic',
      'manageAppVersionAndBuildNumber': False,
  }))
  run(['xcodebuild', '-exportArchive', '-archivePath', archive,
       '-exportOptionsPlist', options, '-exportPath', out / 'export'] + auth,
      ios)
  print('build %s: %s' % (build_number, 'uploaded to App Store Connect'
                          if args.upload else out / 'export' / 'Compass.ipa'))
  return build_number


