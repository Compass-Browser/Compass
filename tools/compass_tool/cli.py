def wrapper_python(layout: Layout) -> str:
  """depot_tools' own Python if available: cc_wrapper and Chromium's
  scripts use it (the signing driver needs 3.11+; macOS ships 3.9)."""
  reldir = layout.depot_tools / 'python3_bin_reldir.txt'
  if reldir.is_file():
    exe = 'python3.exe' if sys.platform == 'win32' else 'python3'
    candidate = layout.depot_tools / reldir.read_text().strip() / exe
    if candidate.is_file():
      return candidate.as_posix()
  return Path(sys.executable).as_posix()


def args_gn(layout: Layout, config: str, cpu: str | None) -> str:
  lines = [
      '# Generated by `compass gen %s`. Shared settings live in' % config,
      '# //compass/config/args/; add local tweaks at the end of this file.',
      'import("//compass/config/args/common.gn")',
      'import("//compass/config/args/%s.gn")' % config,
      'cc_wrapper = "%s ../../compass/build/redirect_cc.py"' %
      wrapper_python(layout),
  ]
  if cpu == 'win-x64':
    # Windows from a Mac (docs/building.md, "Windows from a Mac").
    lines += [
        'target_os = "win"',
        'target_cpu = "x64"',
        # As in the first cross build that ran on Windows (plan.md).
        'v8_use_external_startup_data = false',
    ]
  elif android.is_android(cpu):
    lines += [
        'target_os = "android"',
        'target_cpu = "%s"' % android.TARGETS[cpu],
        'import("//compass/config/args/android.gn")',
    ]
  elif cpu == 'linux-x64':
    # Linux from Windows (docs/building.md, "Linux from Windows").
    lines += [
        'target_os = "linux"',
        'target_cpu = "x64"',
        'import("//compass/config/args/linux.gn")',
    ]
  elif cpu:
    lines.append('target_cpu = "%s"' % cpu)
  return '\n'.join(lines) + '\n'


def product_name(layout: Layout) -> str:
  branding = layout.src / 'chrome/app/theme/chromium/BRANDING'
  for line in branding.read_text().splitlines():
    if line.startswith('PRODUCT_FULLNAME='):
      return line.split('=', 1)[1]
  return 'Chromium'


def browser_binary(layout: Layout, out_dir: Path) -> Path:
  if sys.platform == 'darwin':
    name = product_name(layout)
    return out_dir / (name + '.app') / 'Contents' / 'MacOS' / name
  if sys.platform == 'win32':
    return out_dir / 'chrome.exe'
  return out_dir / 'chrome'


def require_lowercase_name(layout: Layout) -> None:
  # Includes are spelled "compass/...". Clang resolves the src/compass link and
  # rejects a differently cased directory (-Wnonportable-include-path).
  if layout.root.name != 'compass':
    raise CommandError('the repository directory must be named "compass" '
                       '(it is "%s"); rename it and re-run' % layout.root.name)


def require_checkout(layout: Layout) -> None:
  if not (layout.src / '.gn').is_file():
    raise CommandError('no Chromium checkout at %s; run `compass init` first' %
                       layout.src)


def require_linux_cross_host(layout: Layout,
                             platform: str = sys.platform) -> None:
  """--cpu linux-x64 is Linux built on Windows, with its own toolchain."""
  if platform != 'win32':
    raise CommandError(
        '--cpu linux-x64 builds Linux on a Windows host; on Linux, build '
        'without --cpu (docs/building.md, "Linux from Windows")')
  toolchain = layout.src / LINUX_TOOLCHAIN_DIR
  if not (toolchain / 'bin' / 'clang++.exe').is_file():
    raise CommandError(
        'no Linux toolchain in %s: set it up first (docs/building.md, '
        '"Linux from Windows")' % toolchain)


def require_buildable_layout(layout: Layout,
                             platform: str = sys.platform) -> None:
  """Siso on Windows can't see through the src/compass junction."""
  if platform != 'win32' or layout.in_tree:
    return
  link = layout.src / 'compass'
  raise CommandError(
      'on Windows the build needs the in-tree layout: siso does not follow '
      'the directory junction %s (it reports "../../compass/BUILD.gn not '
      'exist"). Move the repository into the checkout, from outside it:\n'
      '  rmdir "%s"\n'
      '  move "%s" "%s"\n'
      '  mklink /J "%s" "%s"   (optional: keeps the old path working)\n'
      'then run compass from %s.' %
      (link, link, layout.root, link, layout.root, link, link))


def cmd_info(layout: Layout, _args) -> None:
  print('repository:       %s' % layout.root)
  print('chromium dir:     %s' % layout.chromium_dir)
  print('layout:           %s' % ('in-tree' if layout.in_tree else 'linked'))
  print('chromium version: %s' % layout.chromium_version())
  print('checkout present: %s' % (layout.src / '.gn').is_file())


def require_in_tree_init(layout: Layout, platform: str = sys.platform) -> None:
  """Stops a Windows `init` that would end in a layout siso can't build."""
  if platform != 'win32' or layout.in_tree:
    return
  target = layout.src / 'compass'
  raise CommandError(
      'on Windows the build needs the in-tree layout (siso does not follow '
      'directory junctions). Clone the repository into the checkout and run '
      'init from there:\n'
      '  git clone <compass repo> "%s"\n'
      '  cd "%s"\n'
      '  tools\\compass.bat init' % (target, target))


def cmd_init(layout: Layout, args) -> None:
  require_lowercase_name(layout)
  require_in_tree_init(layout)
  checkout.init(layout, args.target_os or [checkout.host_os()])
  print('\nDone. Next: compass gen debug && compass build')


def cmd_sync(layout: Layout, _args) -> None:
  require_checkout(layout)
  failures = checkout.update(layout, layout.chromium_version())
  if failures:
    raise CommandError('%d patch(es) failed to apply' % len(failures))


def cmd_update_chromium(layout: Layout, args) -> None:
  require_checkout(layout)
  failures = checkout.update(layout, args.version)
  if failures:
    print('\n%d patch(es) need manual fixes. Resolve the conflicts in src/, '
          'then run `compass patches export`.' % len(failures))
    sys.exit(1)
  orphaned = overrides.orphans(layout.overrides_dir, layout.src)
  if orphaned:
    print('\nOverrides whose upstream file no longer exists:\n  ' +
          '\n  '.join(orphaned))
  print('\nNow on %s. Build, test, then commit patches/ and '
        'config/chromium_version.' % args.version)


def cmd_patches(layout: Layout, args) -> None:
  require_checkout(layout)
  if args.action == 'apply':
    failures = patches.apply(layout.patches_dir, layout.src, args.three_way)
    if failures:
      raise CommandError('%d patch(es) failed to apply' % len(failures))
  elif args.action == 'revert':
    if patches.revert(layout.patches_dir, layout.src):
      raise CommandError('some patches could not be reverted')
  elif args.action == 'export':
    patches.export(layout.patches_dir, layout.src, args.repo or [])
  else:
    for patch, state in patches.status(layout.patches_dir,
                                       layout.src).items():
      print('%-12s %s' % (state,
                          patch.relative_to(layout.patches_dir).as_posix()))


def cmd_gen(layout: Layout, args) -> None:
  require_lowercase_name(layout)
  require_checkout(layout)
  require_buildable_layout(layout)
  out_dir = layout.out_dir(args.config, args.cpu)
  args_file = out_dir / 'args.gn'
  if args.force or not args_file.exists():
    out_dir.mkdir(parents=True, exist_ok=True)
    args_file.write_text(args_gn(layout, args.config, args.cpu))
  if android.is_android(args.cpu):
    # Android needs patches already at gn gen time (BUILDCONFIG's host check,
    # docs/building.md, "Android from a Mac"); elsewhere `build` applies them.
    if not args.skip_patches:
      sync_patches(layout)
    android.prepare_mac_host(layout.src)
  if args.cpu == 'linux-x64':
    require_linux_cross_host(layout)
    # The Windows host toolchains' is_win asserts are patched (docs/building.md,
    # "Linux from Windows"), so patches go in before gn gen too.
    if not args.skip_patches:
      sync_patches(layout)
  run([depot_tool('gn'), 'gen', out_dir.relative_to(layout.src).as_posix()],
      layout.src, env=layout.env())


def cmd_package(layout: Layout, args) -> None:
  """Linux: the .tar.xz, and with --flatpak a Flatpak bundle made from it in
  WSL (docs/building.md, "Linux packages")."""
  if args.cpu != 'linux-x64':
    raise CommandError('package makes Linux packages: pass --cpu linux-x64')
  require_linux_cross_host(layout)
  out_dir = layout.out_dir(args.config, args.cpu)
  if args.build:
    build(layout, args.config, LINUX_PACKAGE_TARGETS, args.jobs,
          args.skip_patches, args.cpu)
  version = args.version or release.new_version()
  strip_tool = layout.src / LINUX_TOOLCHAIN_DIR / 'bin' / 'llvm-strip.exe'
  tarball = linux_package.make_tarball(
      layout.root, layout.src, out_dir, version,
      strip_tool if strip_tool.is_file() else None)
  print('wrote %s' % tarball)
  if args.flatpak:
    stage = linux_package.stage_flatpak(layout.root, tarball, version,
                                        out_dir / 'flatpak')
    bundle = linux_package.build_flatpak(
        stage, out_dir / linux_package.package_name(version, 'flatpak'),
        args.wsl_distro)
    print('wrote %s' % bundle)


def add_skip_patches(parser) -> None:
  parser.add_argument(
      '--skip-patches', action='store_true',
      help='build the checkout as it is, without applying patches/ first')


def sync_patches(layout: Layout) -> None:
  """Applies patches/ as it is now, so a pull's patches go into the build."""
  problems = patches.sync(layout.patches_dir, layout.src)
  if problems:
    raise CommandError(
        'patches/ doesn\'t match the checkout:\n  ' + '\n  '.join(problems) +
        '\nThose files have changes no version of their patch has. Export '
        'them (`compass patches export`) or put them back (`git checkout`), '
        'or build with --skip-patches.')


def build(layout: Layout, config: str, targets, jobs: int | None = None,
          skip_patches: bool = False, cpu: str | None = None) -> Path:
  require_checkout(layout)
  require_buildable_layout(layout)
  out_dir = layout.out_dir(config, cpu)
  if not (out_dir / 'args.gn').exists():
    raise CommandError('%s is not set up; run `compass gen %s%s`' %
                       (out_dir, config, ' --cpu ' + cpu if cpu else ''))
  if cpu == 'linux-x64':
    require_linux_cross_host(layout)
  if not skip_patches:
    sync_patches(layout)
  if android.is_android(cpu):
    android.prepare_mac_host(layout.src)
  if sys.platform == 'darwin':
    # Release builds bundle Sparkle; every build compiles against its
    # headers (docs/design/updates.md).
    sparkle.ensure(layout.root)
  minor = win_build(out_dir / 'args.gn')
  sync_chrome_version(layout.src, minor)
  sync_mojom_salt(layout.src, out_dir, minor)
  for path in overrides.orphans(layout.overrides_dir, layout.src):
    print('warning: override has no upstream file: chromium_src/' + path)
  for path in overrides.sync(layout.overrides_dir, layout.src, out_dir):
    print('override changed, rebuilding: ' + path)
  jobs_args = ['-j', str(jobs)] if jobs else []
  run([depot_tool('autoninja'), '-C', out_dir] + jobs_args + list(targets),
      layout.src, env=layout.env())
  if BROWSER_TEST_TARGET in targets:
    sign_for_tcc(out_dir / BROWSER_TEST_TARGET)
  return out_dir


def sign_for_tcc(binary: Path) -> None:
  """Signs |binary| with the dev identity, if there is one.

  macOS remembers an ad-hoc signed binary's "removable volume" permission by
  its hash, so it asks again after every link. With a stable identity it
  asks once.
  """
  if sys.platform != 'darwin' or not binary.exists():
    return
  identity = next(
      (name for name in DEV_SIGNING_IDENTITIES
       if run(['security', 'find-certificate', '-c', name], binary.parent,
              check=False, capture=True, quiet=True).returncode == 0), None)
  if identity is None:
    return
  info = run(['codesign', '-dvv', binary], binary.parent, check=False,
             capture=True, quiet=True)
  if ('Authority=' + identity) in (info.stdout + info.stderr):
    return
  print('signing %s as "%s"' % (binary.name, identity))
  run(['codesign', '--force', '--sign', identity, '--identifier',
       binary.name, binary], binary.parent)


def cmd_build(layout: Layout, args) -> None:
  build(layout, args.config, args.targets or [DEFAULT_TARGET], args.jobs,
        args.skip_patches, args.cpu)


def passthrough(extra_args):
  """argparse.REMAINDER keeps a leading "--"; the child must not see it."""
  return extra_args[1:] if extra_args[:1] == ['--'] else extra_args


def cmd_run(layout: Layout, args) -> None:
  out_dir = layout.out_dir(args.config, args.cpu)
  binary = browser_binary(layout, out_dir)
  if not binary.exists():
    raise CommandError('%s not found; run `compass build`' % binary)
  profile = out_dir / 'compass-dev-profile'
  if args.fresh and profile.exists():
    shutil.rmtree(profile)
  run([binary, '--user-data-dir=%s' % profile] +
      passthrough(args.browser_args), layout.src, check=False)


def browser_test_args(test_args, headed: bool, platform: str = sys.platform):
  """Switches every browser test run gets, ahead of |test_args|."""
  # Headless browser windows never show or take focus, so tests run in the
  # background. --headed shows them, for watching or debugging a test.
  extra = [] if headed else ['--headless']
  if platform == 'darwin':
    # Upstream launches the GPU process as its own responsible process for
    # macOS privacy (TCC), so it needs its own "removable volume" permission
    # to load the build's dylibs from an external disk, and crashes when that
    # is missing ("GPU process isn't usable"). Kept off, it shares the
    # terminal's access, like every other child process.
    disabled = ['MacDisclaimGpuTccResponsibility']
    rest = []
    for arg in test_args:
      if arg.startswith('--disable-features='):
        disabled += [f for f in arg.split('=', 1)[1].split(',') if f]
      else:
        rest.append(arg)
    extra.append('--disable-features=' + ','.join(disabled))
    test_args = rest
  return extra + list(test_args)


def cmd_test(layout: Layout, args) -> None:
  target = BROWSER_TEST_TARGET if args.browser else TEST_TARGET
  out_dir = build(layout, args.config, [target], args.jobs,
                  args.skip_patches, args.cpu)
  exe = target + ('.exe' if sys.platform == 'win32' else '')
  test_args = passthrough(args.test_args)
  if args.browser:
    test_args = browser_test_args(test_args, args.headed)
  result = run([out_dir / exe] + test_args, layout.src, check=False)
  sys.exit(result.returncode)


def universal_paths(layout: Layout, config: str):
  """The per-CPU apps `compass universal` merges, and the app it makes."""
  app = product_name(layout) + '.app'
  inputs = [layout.out_dir(config, cpu) / app for cpu in CPUS]
  return inputs, layout.out_dir(config, 'universal') / app


def cmd_universal(layout: Layout, args) -> None:
  if sys.platform != 'darwin':
    raise CommandError('universal builds are macOS only')
  require_checkout(layout)
  if args.build:
    for cpu in CPUS:
      build(layout, args.config, [DEFAULT_TARGET], args.jobs, cpu=cpu)
  make_universal(layout, args.config)


def make_universal(layout: Layout, config: str) -> Path:
  """Merges the per-CPU apps into out/<Config>-universal, with the host
  CPU's "<Product> Packaging" (signing scripts and host tools) next to it
  when there is one. Returns that directory."""
  inputs, output = universal_paths(layout, config)
  for app in inputs:
    if not browser_binary(layout, app.parent).is_file():
      raise CommandError('%s not found; build it with `compass build -c %s '
                         '--cpu %s` (or pass --build)' %
                         (app, args.config, app.parent.name.rsplit('-', 1)[1]))
  if output.exists():
    shutil.rmtree(output)
  output.parent.mkdir(parents=True, exist_ok=True)
  run([wrapper_python(layout),
       layout.src / 'chrome/installer/mac/universalizer.py'] + inputs +
      [output], layout.src)
  run(['lipo', '-info', browser_binary(layout, output.parent)], layout.src)
  product = product_name(layout)
  packaging = mac_sign.packaging_dir(layout.out_dir(config, host_cpu()),
                                     product)
  if packaging.is_dir():
    target = mac_sign.packaging_dir(output.parent, product)
    if target.exists():
      shutil.rmtree(target)
    shutil.copytree(packaging, target, symlinks=True)
  print('\nUniversal app: %s' % output)
  return output.parent


def provisioning_profile(args) -> Optional[Path]:
  """The Developer ID provisioning profile to embed, or None (with a
  warning when there's none to find)."""
  if args.no_provisioning_profile:
    return None
  if args.provisioning_profile:
    path = Path(args.provisioning_profile).expanduser()
    if not path.is_file():
      raise CommandError('%s not found' % path)
    return path
  if mac_sign.PROVISIONING_PROFILE.is_file():
    return mac_sign.PROVISIONING_PROFILE
  print('warning: no %s, so no application identifier: other apps\' '
        'browser logins (ASWebAuthenticationSession) won\'t open in this '
        'build. Pass --no-provisioning-profile to silence this.' %
        mac_sign.PROVISIONING_PROFILE, file=sys.stderr)
  return None


def add_provisioning_profile_arguments(s) -> None:
  s.add_argument('--provisioning-profile',
                 help='Developer ID provisioning profile to embed (default: '
                 '%s, when there)' % mac_sign.PROVISIONING_PROFILE)
  s.add_argument('--no-provisioning-profile', action='store_true',
                 help='sign without one, and without the application '
                 'identifier it allows')


def cmd_sign(layout: Layout, args) -> None:
  sign_build(layout, args)


def sign_build(layout: Layout, args) -> Path:
  """Builds (unless --skip-build), signs, packages and notarizes; returns
  the folder with the .dmg."""
  if sys.platform != 'darwin':
    raise CommandError('compass sign is for macOS builds')
  targets = [DEFAULT_TARGET, mac_sign.PACKAGING_TARGET]
  if args.universal:
    if not args.skip_build:
      for cpu in CPUS:
        build(layout, args.config, targets, args.jobs, args.skip_patches, cpu)
    out_dir = make_universal(layout, args.config)
  else:
    out_dir = layout.out_dir(args.config, args.cpu)
    if not args.skip_build:
      build(layout, args.config, targets, args.jobs, args.skip_patches,
            args.cpu)
  product = product_name(layout)
  if not (mac_sign.packaging_dir(out_dir, product) / 'sign_chrome.py').exists():
    raise CommandError('no signing scripts in %s; build %s first' %
                       (mac_sign.packaging_dir(out_dir, product),
                        mac_sign.PACKAGING_TARGET))
  listed = run(['security', 'find-identity', '-v', '-p', 'codesigning'],
               out_dir, capture=True, quiet=True)
  try:
    identity, name = mac_sign.pick_identity(listed.stdout, args.identity)
  except ValueError as e:
    raise CommandError(str(e))
  profile = None if args.no_notarize else args.keychain_profile
  if profile and run(['xcrun', 'notarytool', 'history', '--keychain-profile',
                      profile], out_dir, check=False, capture=True,
                     quiet=True).returncode != 0:
    raise CommandError(mac_sign.store_credentials_hint(
        profile, mac_sign.team_id(name)))
  try:
    app_id = mac_sign.prepare_app_identifier(
        out_dir / (product + '.app'), mac_sign.packaging_dir(out_dir, product),
        mac_sign.team_id(name), provisioning_profile(args))
  except mac_sign.ProfileError as e:
    raise CommandError(str(e))
  if app_id:
    print('application identifier: %s' % app_id)
  output = out_dir / 'signed'
  if output.exists():
    shutil.rmtree(output)
  print('signing as "%s"%s' % (name, ', then notarizing' if profile else ''))
  run(mac_sign.sign_command(wrapper_python(layout), out_dir, product, output,
                            identity, profile), out_dir)
  for dmg in sorted(output.glob('*.dmg')):
    if profile:
      run(['spctl', '--assess', '--type', 'open', '--context',
           'context:primary-signature', '--verbose', dmg], out_dir)
    print('signed: %s' % dmg)
  return output




COMPASS_VERSION_ARG = 'compass_version'
WIN_BUILD_ARG = 'compass_win_build'
# installer/win: Compass's installer with a window.
WIN_INSTALLER_TARGET = 'compass_installer'
WIN_UPDATER_ARG = 'compass_enable_win_updater'


def set_gn_arg(args_file: Path, name: str, value, raw: bool = False) -> None:
  """Sets |name| = "|value|" among args.gn's local tweaks (|raw|: unquoted,
  for numbers and booleans)."""
  lines = [l for l in args_file.read_text().splitlines()
           if not l.startswith(name + ' ') and not l.startswith(name + '=')]
  lines.append('%s = %s' % (name, value if raw else '"%s"' % value))
  args_file.write_text('\n'.join(lines) + '\n')


def gn_arg(args_file: Path, name: str) -> str | None:
  """|name|'s value among args.gn's own lines (not its imports), unquoted."""
  if not args_file.is_file():
    return None
  value = None
  for line in args_file.read_text().splitlines():
    key, sep, rest = line.partition('=')
    if sep and key.strip() == name:
      value = rest.split('#', 1)[0].strip().strip('"')
  return value


def win_build(args_file: Path) -> int:
  value = gn_arg(args_file, WIN_BUILD_ARG)
  try:
    return int(value) if value else 0
  except ValueError:
    raise CommandError('%s: %s = %r is not a number' %
                       (args_file, WIN_BUILD_ARG, value))


def chrome_version(src: Path) -> dict:
  values = {}
  for line in (src / 'chrome' / 'VERSION').read_text().splitlines():
    key, sep, value = line.partition('=')
    if sep:
      values[key.strip()] = value.strip()
  return values


def upstream_chromium_version(src: Path) -> str:
  """chrome/VERSION with upstream's MINOR (0), e.g. "157.0.8103.51"."""
  v = chrome_version(src)
  return '%s.0.%s.%s' % (v['MAJOR'], v['BUILD'], v['PATCH'])


def sync_chrome_version(src: Path, minor: int) -> bool:
  """Writes |minor| (compass_win_build) into chrome/VERSION. Returns whether
  it changed. Every build sets it, so a dev build puts upstream's 0 back."""
  path = src / 'chrome' / 'VERSION'
  if int(chrome_version(src).get('MINOR', '0')) == minor:
    return False
  lines = ['MINOR=%d' % minor if l.startswith('MINOR=') else l
           for l in path.read_text().splitlines()]
  path.write_text('\n'.join(lines) + '\n')
  print('chrome/VERSION: MINOR=%d (%s)' % (minor, WIN_BUILD_ARG))
  return True


MOJOM_SALT_ARG = 'mojom_message_id_salt_path'
MOJOM_SALT = 'build/mojom_message_id_salt'


def sync_mojom_salt(src: Path, out_dir: Path, minor: int) -> None:
  """Official builds scramble Mojo's message IDs with chrome/VERSION as the
  salt (mojo/public/tools/bindings/mojom.gni), so a Windows release's MINOR
  would regenerate every binding and recompile most of Chromium. With a
  MINOR, the salt is upstream's version instead: it still changes with
  every Chromium update, not with every Windows release. It's a source file
  (GN rejects inputs in the out dir that no target generates), ignored by
  git."""
  if minor == 0:
    return
  salt = src / 'compass' / MOJOM_SALT
  text = 'chromium %s\n' % upstream_chromium_version(src)
  if not salt.is_file() or salt.read_text() != text:
    salt.write_text(text)
  args_file = out_dir / 'args.gn'
  value = '//compass/' + MOJOM_SALT
  if gn_arg(args_file, MOJOM_SALT_ARG) != value:
    set_gn_arg(args_file, MOJOM_SALT_ARG, value)


def git_commit(root: Path, short: bool = True,
               mark_dirty: bool = False) -> str:
  """HEAD's hash; with |mark_dirty|, plus "-dirty" when tracked files have
  changes, so a release built from them says so."""
  commit = run(['git', 'rev-parse'] + (['--short'] if short else []) +
               ['HEAD'], root, capture=True, quiet=True).stdout.strip()
  if mark_dirty and run(['git', 'status', '--porcelain', '--untracked-files=no'],
                        root, capture=True, quiet=True).stdout.strip():
    commit += '-dirty'
  return commit


def cmd_release(layout: Layout, args) -> None:
  """Releases: archives on GitHub, feeds on https://updates.compassbrowser.org
  (docs/design/updates.md)."""
  try:
    _release(layout, args)
  except release.ReleaseError as e:
    raise CommandError(str(e))


def _release(layout: Layout, args) -> None:
  manifest = release.load()
  # Everything that writes the feeds starts from the server's releases: a
  # stale local copy would drop the ones it lacks (build-win only reads the
  # server's).
  if args.action in ('publish', 'publish-win', 'promote', 'feeds') and \
      not args.no_upload:
    release.check_against_server(manifest, release.fetch_manifest())
  if args.action == 'list':
    for r in manifest['releases']:
      print('%-15s %-7s %s  chromium %s  %s' % (
          r['version'], r['channel'], r['commit'], r['chromium'],
          ' '.join(p for p in ('mac', 'win') if r.get(p))))
    return
  if args.action == 'promote':
    if not args.version:
      raise CommandError('promote: which version?')
    found = release.find(manifest, args.version)
    if found['channel'] == 'stable':
      raise CommandError('%s is on stable already' % args.version)
    to = args.to or release.promotion(found['channel'])
    if not release.gets(found['channel'], to) or to == found['channel']:
      raise CommandError('%s is on %s: it can only go to a more tested '
                         'channel' % (args.version, found['channel']))
    found['channel'] = to
    feeds = release.write_feeds(manifest)
    if not args.no_upload:
      release.promote_on_github(found)
      release.upload(feeds)
    print('%s is on %s' % (args.version, to))
    return
  if args.action == 'feeds':
    feeds = release.write_feeds(manifest)
    if not args.no_upload:
      release.upload(feeds)
    return
  if args.action == 'build-win':
    build_win(layout, args)
    return
  if args.action == 'publish-win':
    if not args.installer:
      raise CommandError('publish-win: give --installer (the '
                         'CompassSetup-<version>.exe from `compass release '
                         'build-win`, with its .json next to it)')
    installer = Path(args.installer)
    info = win_build_info(installer)
    version = args.version or info.get('version')
    chromium = args.chromium or info.get('chromium', '')
    build_number = args.win_build or info.get('win_build', 0)
    if not version:
      raise CommandError('publish-win: which version? (no %s)' %
                         installer.with_suffix('.json').name)
    # The installer with a window, next to it (build-win's .json names it).
    windowed = installer.parent / (info.get('installer') or
                                   release.win_installer_name(version))
    tools = sparkle.ensure(layout.root) / 'bin'
    added = release.add_win_release(manifest, installer, version, chromium,
                                    args.channel,
                                    info.get('commit') or
                                    git_commit(layout.root),
                                    tools, win_build=build_number,
                                    windowed=windowed
                                    if windowed.is_file() else None)
    feeds = release.write_feeds(manifest)
    if not args.no_upload:
      release.publish_assets(added, release.win_release_files(added),
                             git_commit(layout.root, short=False))
      release.upload(feeds)
    print('released %s for Windows: %s' % (
        added['version'], release.archive_url(added['win'])))
    return
  # publish (macOS): a new version, built, signed, notarized, fed.
  tools = sparkle.ensure(layout.root) / 'bin'
  if not args.skip_build:
    version = args.version or release.new_version()
    for cpu in (CPUS if args.universal else (args.cpu,)):
      set_gn_arg(layout.out_dir(args.config, cpu) / 'args.gn',
                 COMPASS_VERSION_ARG, version)
    print('Compass %s (%s channel)' % (version, args.channel))
  output = sign_build(layout, args)
  dmgs = sorted(output.glob('*.dmg'))
  if len(dmgs) != 1:
    raise CommandError('expected one .dmg in %s, found %d' % (output,
                                                              len(dmgs)))
  added = release.add_mac_release(manifest, dmgs[0], args.channel,
                                  git_commit(layout.root), tools,
                                  notes=args.notes or '')
  feeds = release.write_feeds(manifest)
  if not args.no_upload:
    release.publish_assets(added, release.release_files(added),
                           git_commit(layout.root, short=False))
    release.upload(feeds)
  print('released %s on %s: %s' % (added['version'], args.channel,
                                   release.archive_url(added['mac'])))


def win_build_info(installer: Path) -> dict:
  """What build-win wrote next to the installer, or {}."""
  sidecar = installer.with_suffix('.json')
  if not sidecar.is_file():
    return {}
  import json
  return json.loads(sidecar.read_text())


def build_win(layout: Layout, args) -> Path:
  """Windows: builds the installer for a release, numbered so Chromium's
  installer updates to it. Prints the file for `release publish-win`, which
  runs where the release key is (docs/design/updates.md, "Windows")."""
  if sys.platform != 'win32' and args.cpu != 'win-x64':
    raise CommandError('build-win runs on Windows, or on a Mac with --cpu '
                       'win-x64 (docs/building.md, "Windows from a Mac")')
  version = args.version or release.new_version()
  manifest = release.fetch_manifest()
  if any(r['version'] == version and r.get('win')
         for r in manifest['releases']):
    raise CommandError('release %s has a Windows installer already' % version)
  number = args.win_build or release.next_win_build(manifest)
  out_dir = layout.out_dir(args.config, args.cpu)
  args_file = out_dir / 'args.gn'
  if not args_file.exists():
    cmd_gen(layout, argparse.Namespace(config=args.config, cpu=args.cpu,
                                       force=False))
  set_gn_arg(args_file, COMPASS_VERSION_ARG, version)
  set_gn_arg(args_file, WIN_BUILD_ARG, number, raw=True)
  set_gn_arg(args_file, WIN_UPDATER_ARG, 'true', raw=True)
  chromium = upstream_chromium_version(layout.src)
  installer_version = chromium.replace('.0.', '.%d.' % number, 1)
  print('Compass %s for Windows: installer version %s' % (version,
                                                       installer_version))
  # mini_installer packs every <version>.manifest in the out dir, so earlier
  # builds' would ride along in the version folder.
  for manifest in out_dir.glob('*.*.*.*.manifest'):
    if manifest.name != installer_version + '.manifest':
      manifest.unlink()
  build(layout, args.config,
        ['chrome', 'mini_installer', WIN_INSTALLER_TARGET], args.jobs,
        args.skip_patches, args.cpu)
  setup = out_dir / ('CompassSetup-%s.exe' % version)
  shutil.copyfile(out_dir / 'mini_installer.exe', setup)
  # The one with a window, for the website (installer/win).
  installer = out_dir / release.win_installer_name(version)
  shutil.copyfile(out_dir / (WIN_INSTALLER_TARGET + '.exe'), installer)
  import json
  setup.with_suffix('.json').write_text(json.dumps({
      'version': version,
      'chromium': chromium,
      'win_build': number,
      'commit': git_commit(layout.root, mark_dirty=True),
      'installer': installer.name,
  }, indent=2) + '\n')
  print('built %s and %s\npublish them from the release Mac: compass '
        'release publish-win --installer CompassSetup-%s.exe (with its .json '
        'and %s)' % (setup, installer, version, installer.name))
  return setup




def cmd_sync_server(layout: Layout, args) -> None:
  if args.podman:
    if args.fresh:
      run(['podman', 'volume', 'rm', '-f', sync_server.VOLUME], layout.root)
    for cmd, cwd in sync_server.podman_commands(layout.root, args.port):
      run(cmd, cwd)
    return
  cmd, cwd, env = sync_server.go_command(layout.root, args.port)
  data = sync_server.data_dir(layout.root)
  if args.fresh and data.exists():
    shutil.rmtree(data)
  data.mkdir(parents=True, exist_ok=True)
  print('sync server on http://localhost:%d/v2 (data in %s)' % (args.port,
                                                                data))
  run(cmd, cwd, env=env, check=False)


