import os
import re
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import update_emoji_data as update  # noqa: E402

GROUP_LINES = ''.join('# group: %s\n' % group for group in update.GROUPS
                      if group != 'Smileys & Emotion')

EMOJI_TEST = '''# group: Smileys & Emotion

# subgroup: face-smiling
1F600 ; fully-qualified # 😀 E1.0 grinning face
263A FE0F ; fully-qualified # ☺️ E0.6 smiling face
263A ; unqualified # ☺ E0.6 smiling face
1FAE9 ; fully-qualified # 🫩 E16.0 face with bags under eyes

# group: Component
1F3FB ; component # 🏻 E1.0 light skin tone

# group: People & Body
1F44B ; fully-qualified # 👋 E0.6 waving hand
1F44B 1F3FB ; fully-qualified # 👋🏻 E1.0 waving hand: light skin tone
''' + GROUP_LINES.replace('# group: People & Body\n', '')

ANNOTATIONS = '''<ldml><annotations>
<annotation cp="😀">face | grin | Happy</annotation>
<annotation cp="😀" type="tts">grinning face</annotation>
<annotation cp="☺">smile | face</annotation>
<annotation cp="☺" type="tts">smiling face</annotation>
</annotations></ldml>'''


class UpdateEmojiDataTest(unittest.TestCase):

  def test_keeps_fully_qualified_emoji_up_to_the_version(self):
    groups = dict(update.parse_emoji_test(EMOJI_TEST))
    self.assertNotIn('Component', groups)
    self.assertEqual([e for e, _ in groups['Smileys & Emotion']],
                     ['😀', '☺️'])
    # No skin tone variants.
    self.assertEqual([e for e, _ in groups['People & Body']], ['👋'])

  def test_refuses_missing_groups(self):
    with self.assertRaises(ValueError):
      update.parse_emoji_test('# group: Smileys & Emotion\n')

  def test_names_and_keywords_from_cldr(self):
    text, count = update.build(
        update.parse_emoji_test(EMOJI_TEST),
        update.parse_annotations(ANNOTATIONS))
    self.assertEqual(count, 3)
    # Keywords leave out the name's words, lower case.
    self.assertIn('😀\\tgrinning face\\tgrin happy', text)
    # Found without U+FE0F, as CLDR has it.
    self.assertIn('☺️\\tsmiling face\\tsmile', text)
    # No annotation: emoji-test.txt's name.
    self.assertIn('👋\\twaving hand\\t', text)

  def test_shipped_data_is_current_format(self):
    with open(update.OUT, encoding='utf-8') as f:
      text = f.read()
    self.assertIn('Generated by tools/update_emoji_data.py', text)
    ids = re.findall(r'id: "([a-z]+)"', text)
    self.assertEqual(ids, [gid for gid, _, _ in update.GROUPS.values()])


if __name__ == '__main__':
  unittest.main()
