"""Writes a C++ header that holds text files as string constants.

  embed_text.py --out x.h --namespace a::b NAME=path [NAME=path ...]

Each NAME becomes `inline constexpr std::string_view NAME`, the file's
bytes. Used for common/claude/ (docs/design/claude.md), which desktop builds
into the browser and iOS ships as bundle resources.
"""

import argparse
import os


def main():
  parser = argparse.ArgumentParser()
  parser.add_argument('--out', required=True)
  parser.add_argument('--namespace', required=True)
  parser.add_argument('files', nargs='+')
  args = parser.parse_args()

  guard = os.path.basename(args.out).upper().replace('.', '_') + '_'
  lines = [
      '// Generated by //compass/build/embed_text.py. Do not edit.',
      '#ifndef ' + guard,
      '#define ' + guard,
      '',
      '#include <string_view>',
      '',
      'namespace %s {' % args.namespace,
      '',
  ]
  for item in args.files:
    name, path = item.split('=', 1)
    with open(path, encoding='utf-8') as f:
      text = f.read()
    delimiter = 'compass_embed'
    if (')' + delimiter + '"') in text:
      raise SystemExit('%s holds the raw string delimiter' % path)
    lines.append('// %s' % os.path.basename(path))
    lines.append('inline constexpr std::string_view %s = R"%s(%s)%s";' %
                 (name, delimiter, text, delimiter))
    lines.append('')
  lines += ['}  // namespace %s' % args.namespace, '', '#endif  // ' + guard,
            '']
  os.makedirs(os.path.dirname(args.out), exist_ok=True)
  with open(args.out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))


if __name__ == '__main__':
  main()
