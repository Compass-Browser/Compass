# Regenerates ios/CompassKit/Sources/SyncProto from Chromium's sync protos at
# the pinned version (config/chromium_version), with Compass's
# EntitySpecifics patch and compass_spaces_specifics.proto. The output is
# committed, so building the app needs neither protoc nor a checkout.
#
# Usage: gen_protos.sh [chromium src]   (default: the `compass info` checkout)
# Needs: protoc and protoc-gen-swift (brew install swift-protobuf). The
# SwiftProtobuf package in CompassKit/Package.swift must match the
# generator's version.
#
# Until sync-main is merged into main, the Compass files are read from
# $COMPASS_SYNC_REF (default origin/sync-main) when they aren't in the tree.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
src="${1:-}"
if [[ -z "$src" ]]; then
  src="$("$repo/tools/compass" info | sed -n 's/^chromium dir: *//p')/src"
fi
if [[ ! -f "$src/chrome/VERSION" ]]; then
  echo "error: no Chromium checkout at $src; pass its src directory" >&2
  exit 1
fi
ref="${COMPASS_SYNC_REF:-origin/sync-main}"
out="$here/../CompassKit/Sources/SyncProto"

want="$(tr -d '[:space:]' < "$repo/config/chromium_version")"
have="$(. "$src/chrome/VERSION"; echo "$MAJOR.$MINOR.$BUILD.$PATCH")"
if [[ "$want" != "$have" ]]; then
  echo "error: checkout $src is $have, config/chromium_version says $want" >&2
  exit 1
fi

# A repo file, or the same file on $ref.
repo_file() {
  if [[ -f "$repo/$1" ]]; then cat "$repo/$1"; else git -C "$repo" show "$ref:$1"; fi
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
proto="$tmp/components/sync/protocol"
mkdir -p "$proto" "$tmp/compass/components/sync/protocol"
cp "$src/components/sync/protocol/"*.proto "$proto/"
# The upstream checkout may already carry the patch (applied by `compass
# patches apply`); only patch a clean file.
if ! grep -q compass_spaces "$proto/entity_specifics.proto"; then
  repo_file patches/components-sync-protocol-entity_specifics.proto.patch |
    patch -s -d "$tmp" -p1
fi
repo_file components/sync/protocol/compass_spaces_specifics.proto \
  > "$tmp/compass/components/sync/protocol/compass_spaces_specifics.proto"

rm -rf "$out"
mkdir -p "$out"
include="$(dirname "$(dirname "$(command -v protoc)")")/include"
(cd "$tmp" && protoc --proto_path=. --proto_path="$include" \
  --swift_out="$out" \
  --swift_opt=Visibility=Public --swift_opt=FileNaming=DropPath \
  components/sync/protocol/*.proto \
  compass/components/sync/protocol/compass_spaces_specifics.proto)

cat > "$out/README.md" <<EOT
Generated by ios/scripts/gen_protos.sh from Chromium $want's
components/sync/protocol plus Compass's compass_spaces_specifics.proto
($(protoc-gen-swift --version)). Don't edit; rerun the script.
EOT
echo "$(ls "$out"/*.swift | wc -l | tr -d ' ') files in $out"
